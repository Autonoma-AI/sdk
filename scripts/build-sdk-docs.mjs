#!/usr/bin/env node
/**
 * Assemble the bundled agent-facing docs for every published SDK package.
 *
 * Single source of truth:
 *   docs/shared/*.md, docs/shared/llms.txt   - language-agnostic, copied verbatim
 *   docs/languages/<lang>/*.md               - language-specific (implement, factories, validation)
 *   docs/languages/<lang>/AGENTS.md          - the package-root pointer file
 *
 * For each target package this writes:
 *   <docsDir>/{overview,protocol,scenarios,implement,factories,validation}.md
 *   <docsDir>/llms.txt
 *   <agentsDir>/AGENTS.md
 *
 * The outputs are committed so each package manifest can ship them without a
 * per-toolchain build hook. Re-run this after editing any doc source:
 *   node scripts/build-sdk-docs.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SHARED = join(ROOT, 'docs', 'shared')
const LANGS = join(ROOT, 'docs', 'languages')

const SHARED_MD = ['overview.md', 'protocol.md', 'scenarios.md']
const LANG_MD = ['implement.md', 'factories.md', 'validation.md']
const GENERATED_NOTE = (src) =>
  `<!-- Generated by scripts/build-sdk-docs.mjs from ${src}. Edit the source, not this copy. -->\n`

/**
 * Each target is one published package.
 *   lang      - key under docs/languages/
 *   docsDir   - where the doc set lands (shipped by the package manifest)
 *   agentsDir - where AGENTS.md lands (usually the package root)
 */
const TARGETS = [
  // TypeScript - one bundle per published package so it is found no matter
  // which package the agent opens first.
  { lang: 'typescript', docsDir: 'sdks/typescript/packages/sdk/docs', agentsDir: 'sdks/typescript/packages/sdk' },
  { lang: 'typescript', docsDir: 'sdks/typescript/packages/server-web/docs', agentsDir: 'sdks/typescript/packages/server-web' },
  { lang: 'typescript', docsDir: 'sdks/typescript/packages/server-express/docs', agentsDir: 'sdks/typescript/packages/server-express' },
  { lang: 'typescript', docsDir: 'sdks/typescript/packages/server-hono/docs', agentsDir: 'sdks/typescript/packages/server-hono' },
  { lang: 'typescript', docsDir: 'sdks/typescript/packages/server-node/docs', agentsDir: 'sdks/typescript/packages/server-node' },

  // Python - shipped as package data under the importable `autonoma` package.
  { lang: 'python', docsDir: 'sdks/python/src/autonoma/docs', agentsDir: 'sdks/python/src/autonoma' },

  // Elixir - shipped via mix.exs `files`.
  { lang: 'elixir', docsDir: 'sdks/elixir/docs', agentsDir: 'sdks/elixir' },

  // PHP - Composer ships the whole tracked tree.
  { lang: 'php', docsDir: 'sdks/php/docs', agentsDir: 'sdks/php' },

  // Java - copied into the JAR via a Maven <resource> under autonoma/docs.
  { lang: 'java', docsDir: 'sdks/java/autonoma-sdk/src/main/resources/autonoma/docs', agentsDir: 'sdks/java/autonoma-sdk/src/main/resources/autonoma' },

  // Ruby - shipped via a broadened gemspec `files` glob.
  { lang: 'ruby', docsDir: 'sdks/ruby/docs', agentsDir: 'sdks/ruby' },

  // Rust - Cargo ships the crate tree.
  { lang: 'rust', docsDir: 'sdks/rust/docs', agentsDir: 'sdks/rust' },

  // Go - `go get` fetches the whole module tree.
  { lang: 'go', docsDir: 'sdks/go/docs', agentsDir: 'sdks/go' },
]

function copyWithNote(srcPath, destPath, srcLabel) {
  const body = readFileSync(srcPath, 'utf-8')
  const out = destPath.endsWith('.md') ? GENERATED_NOTE(srcLabel) + body : body
  mkdirSync(dirname(destPath), { recursive: true })
  writeFileSync(destPath, out)
}

let wrote = 0
let skipped = 0
for (const t of TARGETS) {
  const langDir = join(LANGS, t.lang)
  if (!existsSync(langDir)) {
    console.warn(`skip ${t.docsDir} - no language docs at docs/languages/${t.lang} yet`)
    skipped++
    continue
  }
  const docsDir = join(ROOT, t.docsDir)
  mkdirSync(docsDir, { recursive: true })

  for (const f of SHARED_MD) copyWithNote(join(SHARED, f), join(docsDir, f), `docs/shared/${f}`)
  copyWithNote(join(SHARED, 'llms.txt'), join(docsDir, 'llms.txt'), 'docs/shared/llms.txt')
  for (const f of LANG_MD) copyWithNote(join(langDir, f), join(docsDir, f), `docs/languages/${t.lang}/${f}`)
  copyWithNote(join(langDir, 'AGENTS.md'), join(ROOT, t.agentsDir, 'AGENTS.md'), `docs/languages/${t.lang}/AGENTS.md`)

  console.log(`ok   ${t.docsDir}  (+ ${t.agentsDir}/AGENTS.md)`)
  wrote++
}

console.log(`\n${wrote} package(s) written, ${skipped} skipped (missing language docs).`)
